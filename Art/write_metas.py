def write(path, template):
    if not os.path.exists(path):
        with open(path, "w") as f:
            f.write(template.format(guid=uuid.uuid4().hex))
        print("wrote", os.path.relpath(path, ROOT))


def main():
    for folder in [ROOT] + sorted(glob.glob(os.path.join(ROOT, "DickinsonSprites", "**", ""), recursive=True)):
        write(folder.rstrip(os.sep) + ".meta", FOLDER)
    for png in sorted(glob.glob(os.path.join(ROOT, "DickinsonSprites", "**", "*.png"), recursive=True)):
        write(png + ".meta", TEXTURE)


if __name__ == "__main__":
    main()
